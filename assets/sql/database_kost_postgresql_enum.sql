-- ============================================================
-- 2. DEFINISI ENUM
-- ============================================================

CREATE TYPE role_user AS ENUM (
    'penghuni',
    'pengelola'
);

CREATE TYPE status_kunjungan AS ENUM (
    'menunggu',
    'dikonfirmasi',
    'selesai',
    'dibatalkan'
);

CREATE TYPE status_booking AS ENUM (
    'menunggu',
    'dikonfirmasi',
    'kadaluarsa'
);

CREATE TYPE status_pengaduan AS ENUM (
    'diajukan',
    'diproses',
    'selesai'
);

CREATE TYPE status_pembayaran AS ENUM (
    'menunggu',
    'belumdibayar',
    'lunas',
    'terlambat'
);

CREATE TYPE tipe_kamar AS ENUM (
    'standar',
    'premium'
);

CREATE TYPE status_kamar AS ENUM (
    'terisi',
    'kosong',
    'booking',
    'diperbaiki'
);

CREATE TYPE status_fasilitas AS ENUM (
    'diperbaiki',
    'normal'
);

CREATE TYPE kategori_fasilitas AS ENUM (
    'umum',
    'private'
);

-- ============================================================
-- 3. TABEL USER
-- ============================================================
CREATE TABLE "user" (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role     role_user    NOT NULL,
    username VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    nama     VARCHAR(100) NOT NULL
);

-- ============================================================
-- 4. TABEL KAMAR
-- userid mengacu pada penghuni yang menempati kamar.
-- userid boleh NULL jika kamar belum ditempati.
-- ============================================================
CREATE TABLE kamar (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid      INTEGER,
    ukuran      VARCHAR(30)   NOT NULL,
    harga       DECIMAL(12,2) NOT NULL CHECK (harga >= 0),
    status      status_kamar  NOT NULL,
    nomor_kamar VARCHAR(20)   NOT NULL UNIQUE,
    foto        VARCHAR(100),
    tipe        tipe_kamar    NOT NULL,

    CONSTRAINT fk_kamar_user
        FOREIGN KEY (userid) REFERENCES "user"(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

-- ============================================================
-- 5. TABEL FASILITAS
-- ============================================================
CREATE TABLE fasilitas (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama     VARCHAR(255)       NOT NULL,
    kategori kategori_fasilitas NOT NULL
);

-- ============================================================
-- 6. TABEL KAMAR_FASILITAS
-- Tabel penghubung kamar dengan fasilitas.
-- ============================================================
CREATE TABLE kamar_fasilitas (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fasilitasid INTEGER NOT NULL,
    kamarid     INTEGER NOT NULL,
    status      status_fasilitas NOT NULL,

    CONSTRAINT fk_kamar_fasilitas_fasilitas
        FOREIGN KEY (fasilitasid) REFERENCES fasilitas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_kamar_fasilitas_kamar
        FOREIGN KEY (kamarid) REFERENCES kamar(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT uq_kamar_fasilitas
        UNIQUE (fasilitasid, kamarid)
);

-- ============================================================
-- 7. TABEL BOOKING
-- ============================================================
CREATE TABLE booking (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kamarid        INTEGER NOT NULL,
    status         status_booking NOT NULL,
    tgl_booking    DATE NOT NULL DEFAULT CURRENT_DATE,
    batas_waktu    DATE NOT NULL,
    calon_penghuni VARCHAR(100) NOT NULL,

    CONSTRAINT fk_booking_kamar
        FOREIGN KEY (kamarid) REFERENCES kamar(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_booking_batas_waktu
        CHECK (batas_waktu >= tgl_booking)
);

-- ============================================================
-- 8. TABEL PEMBAYARAN
-- ============================================================
CREATE TABLE pembayaran (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid           INTEGER NOT NULL,
    kamarid          INTEGER NOT NULL,
    tanggal_tagihan  DATE NOT NULL DEFAULT CURRENT_DATE,
    jatuh_tempo      DATE NOT NULL,
    status           status_pembayaran NOT NULL DEFAULT 'menunggu',
    bukti_pembayaran VARCHAR(255),
    jumlah           DECIMAL(12,2) NOT NULL CHECK (jumlah >= 0),

    CONSTRAINT fk_pembayaran_user
        FOREIGN KEY (userid) REFERENCES "user"(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pembayaran_kamar
        FOREIGN KEY (kamarid) REFERENCES kamar(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- ============================================================
-- 9. TABEL PENGADUAN
-- kamar_fasilitas_id mengacu pada fasilitas di kamar tertentu.
-- tanggal_perbaikan NULL berarti belum ada tanggal perbaikan.
-- ============================================================
CREATE TABLE pengaduan (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid             INTEGER NOT NULL,
    kamar_fasilitas_id INTEGER NOT NULL,
    deskripsi          VARCHAR(1000) NOT NULL,
    foto               VARCHAR(255),
    status             status_pengaduan NOT NULL DEFAULT 'diajukan',
    tanggal_pengaduan  DATE NOT NULL DEFAULT CURRENT_DATE,
    tanggal_perbaikan  DATE,

    CONSTRAINT fk_pengaduan_user
        FOREIGN KEY (userid) REFERENCES "user"(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pengaduan_kamar_fasilitas
        FOREIGN KEY (kamar_fasilitas_id) REFERENCES kamar_fasilitas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_pengaduan_tanggal_perbaikan
        CHECK (
            tanggal_perbaikan IS NULL
            OR tanggal_perbaikan >= tanggal_pengaduan
        )
);

-- ============================================================
-- 10. TABEL KUNJUNGAN
-- Pada PDM yang diberikan, tabel kunjungan belum memiliki FK.
-- ============================================================
CREATE TABLE kunjungan (
    id_kunjungan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         VARCHAR(100) NOT NULL,
    tanggal      DATE NOT NULL,
    status       status_kunjungan NOT NULL DEFAULT 'menunggu'
);

-- ============================================================
-- 11. INDEX UNTUK KOLOM FOREIGN KEY
-- ============================================================
CREATE INDEX idx_kamar_userid
    ON kamar(userid);

CREATE INDEX idx_kamar_fasilitas_fasilitasid
    ON kamar_fasilitas(fasilitasid);

CREATE INDEX idx_kamar_fasilitas_kamarid
    ON kamar_fasilitas(kamarid);

CREATE INDEX idx_booking_kamarid
    ON booking(kamarid);

CREATE INDEX idx_pembayaran_userid
    ON pembayaran(userid);

CREATE INDEX idx_pembayaran_kamarid
    ON pembayaran(kamarid);

CREATE INDEX idx_pengaduan_userid
    ON pengaduan(userid);

CREATE INDEX idx_pengaduan_kamar_fasilitas_id
    ON pengaduan(kamar_fasilitas_id);

